#!/usr/bin/env python3
"""Publication-grade maps of verified V5 *photo-derived three-trait* 5-degree cells.

Input was generated by Actions run 44514111389 from the exact confidential
source with the original WCVP native/introduced status, five annual CHELSA
variables and three measured capitulum traits. The public CSV contains only
5-degree bins with >=5 source measurement records; plot symbols represent
CELL CENTROIDS, not individual photographic or personal GPS coordinates.
"""
from pathlib import Path
import argparse
import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from mpl_toolkits.basemap import Basemap

EXPECTED = {
  ("Cirsium arvense","native"):(106,18381),
  ("Cirsium arvense","introduced"):(71,22237),
  ("Cirsium vulgare","native"):(78,13051),
  ("Cirsium vulgare","introduced"):(95,25472)
}
COLORS = {"native":"#2b689a","introduced":"#198b77"}

def plot(data, out):
    fig, axes=plt.subplots(2,2,figsize=(11,6.3))
    for i,species in enumerate(["Cirsium arvense","Cirsium vulgare"]):
        for j,range_state in enumerate(["native","introduced"]):
            ax=axes[i,j]
            r=data.loc[(data.species==species)&(data.range_state==range_state)]
            exp_n,exp_records=EXPECTED[species,range_state]
            assert (len(r),int(r.record_count.sum()))==(exp_n,exp_records)
            m=Basemap(projection="moll",lon_0=0,resolution="c",ax=ax)
            m.drawmapboundary(fill_color="white",color="#a4b0ba",linewidth=.45)
            m.fillcontinents(color="#e9eef1",lake_color="white",zorder=1)
            m.drawcoastlines(color="#acb6bd",linewidth=.4,zorder=2)
            lon=-180+5*r.lon_bin.to_numpy()+2.5
            lat=-90+5*r.lat_bin.to_numpy()+2.5
            x,y=m(lon,lat)
            sizes=10+15*np.log10(r.record_count.to_numpy()+1)
            ax.scatter(x,y,s=sizes,c=COLORS[range_state],alpha=.88,
                       edgecolors="white",linewidths=.15,zorder=3)
            ax.set_title(f"({chr(97+2*i+j)}) {species} · {range_state}: {len(r)} cells",
                         loc="left",fontsize=11,fontweight="bold")
            ax.set_axis_off()
    fig.suptitle("V5 photographed capitulum trait coverage (privacy-filtered 5-degree cells)",
                 fontsize=15,fontweight="bold")
    fig.text(.5,.05,"Exact V5 three-trait and annual five-climate cohort (79,421 records); "
             "350 shown 5° cells (79,141 records), 280 records suppressed in cells n<5.",
             ha="center",fontsize=9)
    fig.text(.5,.025,"Symbols denote 5-degree-cell centres; no exact photo GPS locations are displayed.",
             ha="center",fontsize=9,color="#637280")
    fig.subplots_adjust(top=.86,bottom=.12,left=.02,right=.98,hspace=.25,wspace=.07)
    out.mkdir(parents=True,exist_ok=True)
    for suffix in ("svg","pdf","png"):
        fig.savefig(out/f"v5_three_trait_photo_coverage_5deg.{suffix}",dpi=300,
                    bbox_inches="tight",pad_inches=.08)
    plt.close(fig)

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--source",type=Path,default=Path(
      "manuscripts/v5_annual_20261111/figures/v5_photo_coverage_5deg_public.csv"))
    p.add_argument("--out",type=Path,default=Path(
      "manuscripts/v5_annual_20261111/figures/generated"))
    args=p.parse_args()
    d=pd.read_csv(args.source)
    assert set(d)=={"species","range_state","lat_bin","lon_bin","record_count"}
    assert len(d)==350 and int(d.record_count.sum())==79141
    assert d.record_count.ge(5).all() and d.lat_bin.between(0,35).all() and d.lon_bin.between(0,71).all()
    plot(d,args.out)
if __name__=="__main__":
    main()
